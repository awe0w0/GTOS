#ifndef GTOS_COMMON_VERSION_H
#define GTOS_COMMON_VERSION_H

#define GTOS_VERSION_MAJOR 0
#define GTOS_VERSION_MINOR 3
#define GTOS_VERSION_PATCH 0

#define GTOS_VERSION_STRINGIFY_VALUE(value) #value
#define GTOS_VERSION_STRINGIFY(value) GTOS_VERSION_STRINGIFY_VALUE(value)
#define GTOS_VERSION_RELEASE \
    GTOS_VERSION_STRINGIFY(GTOS_VERSION_MAJOR) "." \
    GTOS_VERSION_STRINGIFY(GTOS_VERSION_MINOR)
#define GTOS_VERSION_STRING \
    GTOS_VERSION_RELEASE "." GTOS_VERSION_STRINGIFY(GTOS_VERSION_PATCH)

#endif
